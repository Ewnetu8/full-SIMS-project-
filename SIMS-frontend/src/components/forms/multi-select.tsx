function Tag({ label, onRemove }: { label: string; onRemove: (e: React.MouseEvent) => void }) {
  return (
    <span className="inline-flex items-center gap-1 rounded-md bg-secondary px-2 py-0.5 text-xs font-medium text-secondary-foreground">
      {label}
      <button
        type="button"
        onClick={onRemove}
        aria-label={`Remove ${label}`}
        className="text-secondary-foreground/60 hover:text-secondary-foreground transition-colors"
      >
        <X className="h-3 w-3" />
      </button>
    </span>
  );
}
