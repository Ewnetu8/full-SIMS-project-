/**
 * Multi-select with tag pills, keyboard navigation, and search filtering.
 *
 * @example
 * <MultiSelect
 *   options={courseOptions}
 *   value={selected}
 *   onChange={setSelected}
 *   placeholder="Select courses"
 * />
 */
export function MultiSelect<T = string>({
  options,
  value = [],
  onChange,
  placeholder = 'Select options',
  maxDisplay = 3,
  disabled = false,
  error = false,
  className,
}: MultiSelectProps<T>) {
  const [open,   setOpen]   = React.useState(false);
  const [search, setSearch] = React.useState('');

  const toggle = (optValue: T) => {
    const next = value.includes(optValue)
      ? value.filter((v) => v !== optValue)
      : [...value, optValue];
    onChange?.(next);
  };

  const remove = (optValue: T, e: React.MouseEvent) => {
    e.stopPropagation();
    onChange?.(value.filter((v) => v !== optValue));
  };

  const filtered = options.filter((o) =>
    String(o.label).toLowerCase().includes(search.toLowerCase()),
  );

  const selectedLabels = value.map(
    (v) => options.find((o) => o.value === v)?.label ?? String(v),
  );

  return (
    <PopoverPrimitive.Root open={open} onOpenChange={(o) => { setOpen(o); if (!o) setSearch(''); }}>
      <PopoverPrimitive.Trigger asChild>
        <button
          type="button"
          disabled={disabled}
          aria-expanded={open}
          aria-haspopup="listbox"
          className={cn(
            'flex min-h-9 w-full flex-wrap items-center gap-1.5 rounded-lg border bg-background px-3 py-1.5',
            'text-sm transition-all duration-200',
            'focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring',
            'disabled:cursor-not-allowed disabled:opacity-50',
            error ? 'border-destructive' : 'border-input',
            className,
          )}
        >
          {value.length === 0 ? (
            <span className="text-muted-foreground">{placeholder}</span>
          ) : value.length > maxDisplay ? (
            <>
              {selectedLabels.slice(0, maxDisplay).map((label, i) => {
                const selectedValue = value[i];
                return selectedValue === undefined ? null : (
                  <Tag key={String(selectedValue)} label={label} onRemove={(e) => remove(selectedValue, e)} />
                );
              })}
              <span className="text-xs text-muted-foreground">
                +{value.length - maxDisplay} more
              </span>
            </>
          ) : (
            selectedLabels.map((label, i) => {
              const selectedValue = value[i];
              return selectedValue === undefined ? null : (
                <Tag key={String(selectedValue)} label={label} onRemove={(e) => remove(selectedValue, e)} />
              );
            })
          )}
          <ChevronDown className="ml-auto h-4 w-4 shrink-0 text-muted-foreground" aria-hidden="true" />
        </button>
      </PopoverPrimitive.Trigger>

      <PopoverPrimitive.Portal>
        <PopoverPrimitive.Content
          align="start"
          sideOffset={6}
          style={{ width: 'var(--radix-popover-trigger-width)' }}
          className={cn(
            'z-50 max-h-72 overflow-hidden rounded-lg border border-border bg-popover shadow-md',
            'data-[state=open]:animate-zoom-in focus:outline-none',
          )}
        >
          {/* Search */}
          <div className="border-b border-border px-3 py-2">
            <input
              autoFocus
              placeholder="Search..."
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              className="w-full bg-transparent text-sm outline-none placeholder:text-muted-foreground"
            />
          </div>

          {/* Options */}
          <ul role="listbox" aria-multiselectable="true" className="overflow-y-auto max-h-52 p-1">
            {filtered.length === 0 ? (
              <li className="px-3 py-6 text-center text-sm text-muted-foreground">
                No options found
              </li>
            ) : (
              filtered.map((opt) => {
                const selected = value.includes(opt.value);
                return (
                  <li
                    key={String(opt.value)}
                    role="option"
                    aria-selected={selected}
                    aria-disabled={opt.disabled}
                    onClick={() => !opt.disabled && toggle(opt.value)}
                    className={cn(
                      'flex cursor-default select-none items-center gap-2 rounded-md px-2 py-1.5 text-sm',
                      'transition-colors',
                      selected
                        ? 'bg-primary/10 text-primary font-medium'
                        : 'hover:bg-accent',
                      opt.disabled && 'pointer-events-none opacity-40',
                    )}
                  >
                    <span className="h-4 w-4 shrink-0 flex items-center justify-center">
                      {selected && <Check className="h-3.5 w-3.5" />}
                    </span>
                    {opt.label}
                  </li>
                );
              })
            )}
          </ul>

          {/* Count footer */}
          <div className="border-t border-border px-3 py-1.5 text-xs text-muted-foreground">
            {value.length} of {options.length} selected
          </div>
        </PopoverPrimitive.Content>
      </PopoverPrimitive.Portal>
    </PopoverPrimitive.Root>
  );
}

